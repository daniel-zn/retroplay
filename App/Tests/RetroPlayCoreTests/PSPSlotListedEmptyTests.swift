import XCTest
@testable import RetroPlayCore

/// iOS's SMB client can list a PSP save slot as empty through every listing though the server
/// holds it (UCUS98648PROFILE00: ICON0.PNG, PARAM.SFO, PIC1.PNG, PROFILE.BIN). Such a slot is
/// read by name: its PARAM.SFO, the data files that lists, and the standard optional files.
final class PSPSlotListedEmptyTests: XCTestCase {
    private let fm = FileManager.default
    private var root: URL!
    private var paths: SavePaths!

    override func setUpWithError() throws {
        root = fm.temporaryDirectory.appendingPathComponent("rp-slot-by-name-\(UUID().uuidString)", isDirectory: true)
        try fm.createDirectory(at: root, withIntermediateDirectories: true)
        paths = SavePaths(documentsURL: root.appendingPathComponent("Documents"))
        try paths.ensureDirectories()
    }

    override func tearDownWithError() throws {
        FolderWalk.bulkListing = nil
        FolderWalk.plainListing = nil
        FolderWalk.pathListing = nil
        FolderWalk.uncoordinatedListing = nil
        DirectoryMetadata.stat = nil
        try? fm.removeItem(at: root)
    }

    private var atv: LibraryGame {
        LibraryGame(displayName: "ATV Offroad Fury Pro", systemID: .psp, relativePath: "ATV.iso", pspProductID: "UCUS98648")
    }

    /// The slot as the share holds it, with every listing of it returning nothing (as on the iPhone).
    private func makeSlot(param: Bool = true) throws -> URL {
        let slot = root.appendingPathComponent("Share/UCUS98648PROFILE00", isDirectory: true)
        try fm.createDirectory(at: slot, withIntermediateDirectories: true)
        if param { try Self.paramSFO.write(to: slot.appendingPathComponent("PARAM.SFO")) }
        for (name, size) in [("PROFILE.BIN", 197_905), ("ICON0.PNG", 900), ("PIC1.PNG", 3_000)] {
            try Data(repeating: 1, count: size).write(to: slot.appendingPathComponent(name))
        }
        let empty: @Sendable (URL) -> [URL]? = { $0.lastPathComponent == "UCUS98648PROFILE00" ? [] : nil }
        FolderWalk.bulkListing = empty
        FolderWalk.plainListing = empty
        FolderWalk.pathListing = empty
        FolderWalk.uncoordinatedListing = empty
        // An SMB share's folder reports a link count of 2 whatever it holds.
        DirectoryMetadata.stat = { _ in (links: 2, dataless: false) }
        return slot
    }

    func testTheRealParamSFOListsItsDataFile() {
        XCTAssertEqual(PSPParamSFO.saveDataFiles(from: Self.paramSFO), ["PROFILE.BIN"])
        XCTAssertNil(PSPParamSFO.discID(from: Self.paramSFO))
    }

    func testTheLibraryImportReadsAnEmptyListedSlotByName() throws {
        let slot = try makeSlot()
        let found = LibrarySaveImporter().plan(SaveFolderScanner.scan([slot]), games: [atv], paths: paths)
        XCTAssertEqual(found.items.map(\.game.displayName), ["ATV Offroad Fury Pro"], "\(found.skipped)")
        XCTAssertEqual(found.skipped, [])
    }

    func testTheInGameImportCopiesAnEmptyListedSlotByName() throws {
        let slot = try makeSlot()
        let importer = SaveGameImporter()
        let plan = try importer.planImport(from: slot, for: atv, paths: paths, fileManager: fm)
        try importer.commitImport(plan: plan, from: slot, overwrite: false, fileManager: fm)
        let copied = try fm.contentsOfDirectory(atPath: plan.destinationURL.path).sorted()
        XCTAssertEqual(copied, ["ICON0.PNG", "PARAM.SFO", "PIC1.PNG", "PROFILE.BIN"])
        XCTAssertEqual(try Data(contentsOf: plan.destinationURL.appendingPathComponent("PARAM.SFO")), Self.paramSFO)
        XCTAssertEqual(try Data(contentsOf: plan.destinationURL.appendingPathComponent("PROFILE.BIN")).count, 197_905)
    }

    func testAnEmptyListedSlotWithoutParamSFOSaysSo() throws {
        let slot = try makeSlot(param: false)
        XCTAssertThrowsError(try SaveGameImporter.validatePSPFolderContents(slot, fileManager: fm)) { error in
            XCTAssertEqual(error as? SaveGameImportError, .pspSlotListedEmpty("UCUS98648PROFILE00"))
            let text = error.localizedDescription
            XCTAssertTrue(text.contains("must include PARAM.SFO"), text)
            XCTAssertTrue(text.contains("iOS listed “UCUS98648PROFILE00” as empty"), text)
            XCTAssertTrue(text.contains("On My iPhone"), text)
        }
        let found = LibrarySaveImporter().plan(SaveFolderScanner.scan([slot]), games: [atv], paths: paths)
        XCTAssertEqual(found.items, [])
        let reason = try XCTUnwrap(found.skipped.first?.reason)
        XCTAssertTrue(reason.hasPrefix("PSP save folders must include PARAM.SFO. iOS listed"), reason)
    }

